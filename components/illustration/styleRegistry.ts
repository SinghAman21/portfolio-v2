function style(
  id: keyof typeof renderers, number: number, group: StyleGroup, name: string,
  description: string, characteristics: string[], useCases: string[],
  rationale: string, limitations: string, implementation: string,
): IllustrationStyle {
  return { id, number, group, name, description, characteristics, useCases, rationale, limitations, implementation, renderer: renderers[id], capabilities: { medium: ["clay", "cinematic", "photobashing"].includes(id) ? "asset" : "vector", motion: false } };
}


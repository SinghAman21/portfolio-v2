export const DEFAULT_STYLE = "technical-ink";
export function findStyle(id: string): IllustrationStyle { return styleRegistry.find((s) => s.id === id) ?? styleRegistry.find((s) => s.id === DEFAULT_STYLE)!; }
export function filterStyles(query: string, group: StyleGroup | "all") {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return styleRegistry.filter((s) => (group === "all" || s.group === group) && terms.every((term) => [s.name, s.description, ...s.characteristics, ...s.useCases, s.rationale].join(" ").toLocaleLowerCase().includes(term)));
}
